/**
 * Font Awesome subset generator.
 *
 * The app ships a full FA Pro `all.css` (~630 KB, ~9200 icon glyph rules) but
 * renders ~90 icons across 3 families (solid / regular / brands). This scans the
 * source for `fa-*` classes and emits `fontawesome.subset.css` containing only
 * the glyph rules we use plus the 3 matching `@font-face` blocks.
 *
 * `npm run build` runs this first; run `npm run fa:subset` by hand after adding
 * or removing an icon so the dev server picks it up. A missing icon renders as a
 * blank box — visible immediately in review.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const faDir = resolve(scriptDir, '../src/assets/fontawesome/css')
const srcDir = resolve(scriptDir, '../src')
const INPUT = resolve(faDir, 'all.css')
const OUTPUT = resolve(faDir, 'fontawesome.subset.css')

// Families the app actually uses. Everything else (duotone / thin / light /
// sharp) is dropped along with its webfont files.
const KEEP_FONT_FILES = ['fa-solid-900.woff2', 'fa-regular-400.woff2', 'fa-brands-400.woff2']

// Selector markers for families we do NOT ship — a non-glyph rule is dropped
// only when every one of its comma-separated selectors carries such a marker.
const UNUSED_FAMILY_MARKERS = [
  '.fad',
  '.fa-duotone',
  '.fass',
  '.fasr',
  '.fasl',
  '.fast',
  '.fa-sharp',
  '.fal',
  '.fa-light',
  '.fat',
  '.fa-thin',
  '.fa-swap-opacity',
  '--fa-primary',
  '--fa-secondary',
]

/** Recursively list `.ts` / `.tsx` files under `dir` (no glob — portable across Node versions). */
function sourceFiles(dir) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...sourceFiles(full))
    else if (/\.tsx?$/.test(entry.name)) out.push(full)
  }
  return out
}

/** Collect every `fa-*` token referenced anywhere in the source tree. */
function collectUsedTokens() {
  const used = new Set()
  for (const file of sourceFiles(srcDir)) {
    for (const m of readFileSync(file, 'utf8').matchAll(/fa-[a-z0-9-]+/g)) used.add(m[0])
  }
  return used
}

/** Walk the stylesheet into top-level chunks: `{ lead, prelude, body }`. */
function parseBlocks(css) {
  const blocks = []
  let i = 0
  let lead = ''
  while (i < css.length) {
    const brace = css.indexOf('{', i)
    if (brace === -1) {
      lead += css.slice(i)
      break
    }
    const prelude = css.slice(i, brace)
    let depth = 1
    let j = brace + 1
    for (; j < css.length && depth > 0; j++) {
      if (css[j] === '{') depth++
      else if (css[j] === '}') depth--
    }
    blocks.push({ lead, prelude: prelude.trim(), body: css.slice(brace + 1, j - 1) })
    lead = ''
    i = j
  }
  return { blocks, trailing: lead }
}

function isGlyphOnly(body) {
  const decls = body
    .split(';')
    .map(d => d.trim())
    .filter(Boolean)
  return decls.length > 0 && decls.every(d => d.replace(/\s/g, '').startsWith('content:'))
}

function preludeTokens(prelude) {
  return Array.from(prelude.matchAll(/fa-[a-z0-9-]+/g), m => m[0])
}

function selectorUsesOnlyUnusedFamilies(prelude) {
  return prelude
    .split(',')
    .map(s => s.trim())
    .every(sel => UNUSED_FAMILY_MARKERS.some(mark => sel.includes(mark)))
}

function main() {
  const used = collectUsedTokens()
  const { blocks, trailing } = parseBlocks(readFileSync(INPUT, 'utf8'))

  let kept = 0
  let dropped = 0
  const out = []
  const emit = (prelude, body) => {
    out.push(`${prelude} {${body.replace(/\s+$/, '\n')}}`)
    kept++
  }

  for (const { prelude, body } of blocks) {
    if (prelude.startsWith('@font-face')) {
      if (!KEEP_FONT_FILES.some(f => body.includes(f))) {
        dropped++
        continue
      }
      // Drop the .ttf fallback — every target browser supports woff2.
      emit(prelude, body.replace(/,\s*url\([^)]*\.ttf'?\)\s*format\('truetype'\)/g, ''))
      continue
    }

    if (prelude.startsWith('@')) {
      emit(prelude, body) // @keyframes / @media / etc — keep verbatim
      continue
    }

    if (isGlyphOnly(body)) {
      if (preludeTokens(prelude).some(t => used.has(t))) emit(prelude, body)
      else dropped++
      continue
    }

    // Non-glyph rule (base / sizing / animation / family mechanics).
    if (selectorUsesOnlyUnusedFamilies(prelude)) dropped++
    else emit(prelude, body)
  }

  const banner =
    `/* GENERATED by scripts/build-fa-subset.mjs — do not edit.\n` +
    `   Source: all.css | kept ${kept} blocks, dropped ${dropped}.\n` +
    `   Regenerate with \`npm run fa:subset\` after changing icons. */\n`
  writeFileSync(OUTPUT, banner + out.join('\n\n') + trailing + '\n')
  console.log(`fa:subset — kept ${kept}, dropped ${dropped} -> ${OUTPUT}`)
}

main()
